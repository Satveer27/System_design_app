"""Records real requests and screenshots, then posts them to a GitHub issue.

Run from the worktree under review:

  evidence.py curl --issue 12 --label "health" --method GET --path api/health
  evidence.py shot --issue 12 --label "palette at 1440px" --file .playwright-mcp/palette.png
  evidence.py post --issue 12 [--dry-run]

Give --path without a leading slash: Git Bash rewrites arguments that start with one.
"""

import argparse
import base64
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

BRANCH = "evidence"
BODY_LIMIT = 4000
SECRET_HEADER = re.compile(r"(?im)^((?:set-cookie|cookie|authorization|x-csrf[\w-]*)\s*:).*$")
SECRET_FIELD = re.compile(
    r'(?i)("[\w-]*(?:password|token|secret|session|csrf)[\w-]*"\s*:\s*)"(?:[^"\\]|\\.)*"'
)
EMAIL = re.compile(r"[\w.+-]+@(?!example\.(?:com|org|test))[\w-]+\.[\w.-]+")


def redact(text: str) -> str:
    """Hides credentials and non-example email addresses."""
    text = SECRET_HEADER.sub(r"\1 <redacted>", text)
    text = SECRET_FIELD.sub(r'\1"<redacted>"', text)
    return EMAIL.sub("<redacted email>", text)


def local_url(port: str, path: str) -> str:
    """A URL on this machine's backend."""
    if "://" in path or re.match(r"^[A-Za-z]:", path):
        raise ValueError(f"--path must be like api/health, got {path!r}")
    return f"http://127.0.0.1:{int(port)}/{path.lstrip('/')}"


def run(command: list[str], stdin: str | None = None) -> str:
    result = subprocess.run(
        command, input=stdin, capture_output=True, text=True, encoding="utf-8", timeout=60
    )
    if result.returncode != 0:
        raise RuntimeError(f"{command[0]} failed: {redact(result.stderr.strip())}")
    return result.stdout


def toplevel() -> Path:
    return Path(run(["git", "rev-parse", "--show-toplevel"]).strip())


def api_port(root: Path) -> str:
    if port := os.environ.get("API_PORT"):
        return port
    for line in (root / ".env").read_text(encoding="utf-8").splitlines():
        if line.startswith("API_PORT="):
            return line.split("=", 1)[1].strip()
    raise RuntimeError("API_PORT is not set")


def record_request(
    port: str, method: str, path: str, headers: list[str], data: str | None, jar: str | None
) -> dict[str, str]:
    """Runs curl and returns the command and its output, redacted."""
    curl = shutil.which("curl")
    if curl is None:
        raise RuntimeError("curl was not found")
    args = ["-sS", "-i", "--max-time", "20", "-X", method.upper()]
    for header in headers:
        args += ["-H", header]
    if data is not None:
        args += ["--data", data]
    if jar:
        args += ["-b", jar, "-c", jar]
    args.append(local_url(port, path))
    result = subprocess.run(
        [curl, *args], capture_output=True, text=True, encoding="utf-8", errors="replace"
    )
    output = result.stdout.replace("\r\n", "\n").strip()
    if result.returncode != 0:
        output += f"\ncurl exit code {result.returncode}: {result.stderr.strip()}"
    if len(output) > BODY_LIMIT:
        output = output[:BODY_LIMIT] + "\n... (truncated)"
    shown = [redact(SECRET_HEADER.sub(r"\1 <redacted>", a)) for a in args]
    return {"command": shlex.join(["curl", *shown]), "output": redact(output)}


def render(entries: list[dict[str, Any]], commit: str) -> str:
    parts = ["## Evidence", f"Generated by `scripts/evidence.py` from commit `{commit}`."]
    for entry in entries:
        parts.append(f"### {entry['label']}")
        if entry["kind"] == "curl":
            parts.append(f"```\n$ {entry['command']}\n{entry['output']}\n```")
        else:
            parts.append(f"![{entry['label']}]({entry.get('url', entry['file'])})")
    return "\n\n".join(parts) + "\n"


def upload(file: Path, issue: int, commit: str) -> str:
    """Commits a screenshot to the evidence branch and returns its URL."""
    try:
        run(["gh", "api", f"repos/{{owner}}/{{repo}}/git/ref/heads/{BRANCH}"])
    except RuntimeError:
        head = run(["gh", "api", "repos/{owner}/{repo}/commits/HEAD", "--jq", ".sha"]).strip()
        run(
            ["gh", "api", "repos/{owner}/{repo}/git/refs", "-f", f"ref=refs/heads/{BRANCH}"]
            + ["-f", f"sha={head}"]
        )
    target = f"issue-{issue}/{commit}-{time.time_ns()}-{re.sub(r'[^\w.-]', '-', file.name)}"
    body = json.dumps(
        {
            "message": f"docs: evidence for #{issue}",
            "branch": BRANCH,
            "content": base64.b64encode(file.read_bytes()).decode(),
        }
    )
    return run(
        ["gh", "api", "-X", "PUT", f"repos/{{owner}}/{{repo}}/contents/{target}"]
        + ["--input", "-", "--jq", ".content.download_url"],
        stdin=body,
    ).strip()


def main(argv: list[str] | None = None) -> int:
    sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[union-attr]
    parser = argparse.ArgumentParser()
    commands = parser.add_subparsers(dest="action", required=True)
    for name in ("curl", "shot", "post"):
        sub = commands.add_parser(name)
        sub.add_argument("--issue", type=int, required=True)
        if name != "post":
            sub.add_argument("--label", required=True)
        if name == "curl":
            sub.add_argument("--method", default="GET")
            sub.add_argument("--path", required=True)
            sub.add_argument("--header", action="append", default=[])
            sub.add_argument("--data")
            sub.add_argument("--cookie-jar")
        if name == "shot":
            sub.add_argument("--file", required=True)
        if name == "post":
            sub.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)

    root = toplevel()
    commit = run(["git", "rev-parse", "--short", "HEAD"]).strip()
    store = root / ".evidence" / f"issue-{args.issue}.json"
    entries = json.loads(store.read_text(encoding="utf-8")) if store.exists() else []

    if args.action == "post":
        if not entries:
            print("no evidence recorded")
            return 1
        if not args.dry_run:
            for entry in entries:
                if entry["kind"] == "shot":
                    entry["url"] = upload(Path(entry["file"]), args.issue, commit)
        text = render(entries, commit)
        if args.dry_run:
            print(text)
            return 0
        print(run(["gh", "issue", "comment", str(args.issue), "--body-file", "-"], stdin=text))
        store.unlink()
        return 0

    if args.action == "curl":
        entry = record_request(
            api_port(root), args.method, args.path, args.header, args.data, args.cookie_jar
        )
        print(f"$ {entry['command']}\n{entry['output']}")
        entry["kind"] = "curl"
    else:
        file = Path(args.file).resolve()
        if file.suffix.lower() != ".png" or not file.is_file():
            print(f"not a PNG file: {args.file}")
            return 1
        entry = {"kind": "shot", "file": str(file)}
        print(f"recorded {file.name}")
    store.parent.mkdir(exist_ok=True)
    store.write_text(json.dumps([*entries, {"label": args.label, **entry}]), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
